//! Small object illustrations. Each object owns its silhouette, front face,
//! lighting and solid colours; the notch's existing navigation icons stay separate.
use crate::render::Canvas;

pub unsafe fn draw(c: &Canvas, kind: usize, x: f32, y: f32, size: f32) {
    let s = size / 24.;
    let r = |a: f32, b: f32, w: f32, h: f32, r: f32, ink: u32| unsafe {
        c.rect(x + a * s, y + b * s, w * s, h * s, r * s, ink)
    };
    let e = |a: f32, b: f32, w: f32, h: f32, ink: u32| unsafe {
        c.ellipse(x + a * s, y + b * s, w * s, h * s, ink)
    };
    let l = |a: f32, b: f32, d: f32, f: f32, w: f32, ink: u32| unsafe {
        c.line((x + a * s, y + b * s), (x + d * s, y + f * s), w * s, ink)
    };
    let p = |points: &[(f32, f32)], ink: u32| unsafe {
        c.polygon(
            &points
                .iter()
                .map(|&(a, b)| (x + a * s, y + b * s))
                .collect::<Vec<_>>(),
            ink,
        )
    };
    match kind {
        0 => {
            r(9., 16., 6., 4., 1., 0x43719e);
            r(5., 20., 14., 2., 1., 0x9dbbd3);
            r(1., 3., 22., 15., 3., 0x25609c);
            r(1., 2., 22., 14., 3., 0x72beef);
            r(3., 4., 18., 10., 1.5, 0x244d83);
            r(4., 5., 16., 7., 1., 0x3f91d0);
            p(&[(4., 5.), (14., 5.), (4., 11.)], 0x7dcbf3);
            l(17., 5., 17., 10., 1., 0xb1e4ff);
            l(14.5, 7.5, 19.5, 7.5, 1., 0xb1e4ff);
        }
        1 => {
            for (row, knob, base, face) in [
                (5., 8., 0x285c58, 0x80d4bb),
                (12., 17., 0x745033, 0xf4bd76),
                (19., 10., 0x443f78, 0xb9a5ed),
            ] {
                r(2., row - 1., 20., 2., 1., base);
                e(knob - 3.5, row - 2.5, 7., 7., base);
                e(knob - 3.5, row - 3.5, 7., 7., face);
                e(knob - 2., row - 2.5, 2., 1.5, 0xe7f9ef);
            }
        }
        2 => {
            r(9., 1., 6., 3., 1., 0xf5c49a);
            r(11., 3., 2., 3., 0.5, 0xc47c55);
            l(18., 5., 20., 7., 2.5, 0xe4a478);
            e(3., 6., 18., 18., 0x9c4e3a);
            e(3., 5., 18., 18., 0xef9d78);
            e(5.5, 7.5, 13., 13., 0xffe3ba);
            l(12., 9., 12., 14., 1.4, 0x744d48);
            l(12., 14., 15.5, 16., 1.4, 0xc75a50);
            e(10.7, 12.7, 2.6, 2.6, 0x744d48);
            l(7., 9., 9., 7.5, 1., 0xfff1dc);
        }
        3 => {
            p(&[(12., 1.), (4.5, 13.), (19.5, 13.)], 0x42b9e9);
            e(4., 8., 16., 16., 0x187bad);
            e(4., 7., 16., 15., 0x42b9e9);
            e(6., 10., 12., 11., 0x309ed1);
            e(6., 8., 4., 8., 0xb4edff);
            e(15., 17., 2.5, 2.5, 0x7cd8fa);
        }
        4 => {
            p(
                &[
                    (7., 5.),
                    (20., 2.),
                    (20., 16.),
                    (17., 17.),
                    (17., 7.),
                    (10., 8.5),
                    (10., 19.),
                    (7., 20.),
                ],
                0x9d4875,
            );
            p(
                &[
                    (7., 4.),
                    (20., 1.),
                    (20., 14.),
                    (17., 15.),
                    (17., 6.),
                    (10., 7.5),
                    (10., 17.),
                    (7., 18.),
                ],
                0xf68fba,
            );
            e(3., 16., 7., 6., 0x9d4875);
            e(3., 15., 7., 5., 0xffb2d0);
            e(13., 13., 7., 6., 0x9d4875);
            e(13., 12., 7., 5., 0xf68fba);
            l(9., 5., 18., 3., 1., 0xffd2e3);
        }
        5 => {
            e(10., 2., 4., 5., 0xeac784);
            e(9., 18., 6., 6., 0xa46832);
            e(9., 18., 6., 4., 0xf7c65d);
            e(5., 4., 14., 16., 0xd89433);
            p(
                &[
                    (5., 11.),
                    (4., 17.),
                    (2., 19.),
                    (22., 19.),
                    (20., 17.),
                    (19., 11.),
                ],
                0xf0b647,
            );
            r(3., 18., 18., 3., 1.5, 0xe5a13b);
            l(8., 9., 8., 13., 2., 0xffdf8e);
        }
        _ => {
            r(2., 3., 20., 20., 4., 0x295a74);
            r(2., 2., 20., 19., 4., 0x7cc7dc);
            r(4., 4., 16., 14., 2.5, 0x173c55);
            e(10.8, 6., 2.4, 2.4, 0xd5f4f9);
            r(11., 10., 2., 5., 1., 0xd5f4f9);
            l(6., 4., 16., 4., 1., 0xb4e6f0);
        }
    }
}
